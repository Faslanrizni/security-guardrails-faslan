# ─────────────────────────────────────────────────────────────────────────────
# Policy loader
# ─────────────────────────────────────────────────────────────────────────────

class Policy:
    """
    Loads and exposes settings from policies/ai-code.yaml.
    Falls back to hardcoded defaults if the file is missing or yaml is unavailable.
    """

    def __init__(self, policy_path: Optional[Path], verbose: bool = False):
        self._verbose = verbose
        self._raw: Dict = {}

        if policy_path and policy_path.exists():
            if not YAML_AVAILABLE:
                self._warn("PyYAML not installed — install it with: pip install pyyaml")
                self._warn("Falling back to hardcoded defaults.")
            else:
                try:
                    with open(policy_path, "r", encoding="utf-8") as f:
                        self._raw = yaml.safe_load(f) or {}
                    self._log(f"Policy loaded from: {policy_path}")
                except Exception as e:
                    self._warn(f"Could not parse policy file: {e}")
                    self._warn("Falling back to hardcoded defaults.")
        else:
            self._warn(f"Policy file not found at {policy_path} — using hardcoded defaults.")

    # ── Accessors ─────────────────────────────────────────────────────────────

    @property
    def enabled(self) -> bool:
        return self._ai.get("detection", {}).get("enabled", True)

    @property
    def flag_threshold(self) -> float:
        return float(self._thresholds.get("flag", DEFAULT_FLAG_THRESHOLD))

    @property
    def block_threshold(self) -> float:
        return float(self._thresholds.get("block", DEFAULT_BLOCK_THRESHOLD))

    @property
    def scan_commit_messages(self) -> bool:
        return self._scan.get("commit_messages", True)

    @property
    def scan_file_content(self) -> bool:
        return self._scan.get("file_content", True)

    @property
    def scan_extensions(self) -> set:
        exts = self._scan.get("extensions", [])
        return set(exts) if exts else DEFAULT_SCAN_EXTENSIONS

    @property
    def exclude_paths(self) -> List[str]:
        return self._scan.get("exclude_paths", DEFAULT_EXCLUDE_PATHS)

    # Tuning weights — fall back to pattern defaults if not set
    @property
    def explicit_ai_signature_weight(self) -> float:
        return float(self._tuning.get("explicit_ai_signature_weight", 0.5))

    @property
    def high_comment_density_weight(self) -> float:
        return float(self._tuning.get("high_comment_density_weight", 0.2))

    @property
    def placeholder_name_weight(self) -> float:
        return float(self._tuning.get("placeholder_name_weight", 0.1))

    # ── Private helpers ───────────────────────────────────────────────────────

    @property
    def _ai(self) -> Dict:
        return self._raw.get("ai_code", {})

    @property
    def _thresholds(self) -> Dict:
        return self._ai.get("thresholds", {})

    @property
    def _scan(self) -> Dict:
        return self._ai.get("scan", {})

    @property
    def _tuning(self) -> Dict:
        return self._ai.get("tuning", {})

    def _log(self, msg: str):
        if self._verbose:
            print(f"  [policy] {msg}")

    def _warn(self, msg: str):
        print(f"  [policy] ⚠ {msg}")

    def summary(self) -> str:
        return (
            f"  flag≥{self.flag_threshold}  "
            f"block≥{self.block_threshold}  "
            f"extensions={len(self.scan_extensions)}  "
            f"exclude_paths={len(self.exclude_paths)}"
        )


